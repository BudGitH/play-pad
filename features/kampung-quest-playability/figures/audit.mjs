// Dev-only: the figures audit (clipping, floating, z-fighting) for every humanoid in Kampung Quest.
// Geometry checks for every head piece (hero boy + girl, all 34 cast / guide / event-actor rigs, every
// crowd and pilgrim hat) and every pose bank, plus close-up turnaround + pose contact sheets on a
// neutral backdrop. Writes figures/audit-<tag>.json, figures/audit-results-<tag>.md and
// figures/sheets-<tag>/*.jpg.
// Run: node tools/serve.mjs 5613 &  then
//   PW_CHROMIUM_PATH=/opt/pw-browsers/chromium node features/kampung-quest-playability/figures/audit.mjs --tag before
//   (add --no-sheets for the numbers only)
import { chromium } from "@playwright/test";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { auditSources, figureScripts, launchArgs } from "./audit-lib.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const BASE = process.env.BASE_URL || "http://localhost:5613";
const args = process.argv.slice(2);
const TAG = args.includes("--tag") ? args[args.indexOf("--tag") + 1] : "now";
const SHEETS = !args.includes("--no-sheets");

/** Open a blank page that has three.js, the figures and the audit helpers loaded. */
async function openPage(browser) {
  const page = await browser.newPage({ viewport: { width: 800, height: 600 } });
  page.on("pageerror", (e) => console.log("PAGEERROR", e.message));
  await page.goto(BASE + "/games/kampung-quest/assets/audio/azan_license.txt");
  const html = figureScripts(BASE).join("\n");
  await page.setContent(`<!doctype html><html><body>${html}</body></html>`, { waitUntil: "load" });
  for (const content of auditSources()) await page.addScriptTag({ content });
  return page;
}

/** One markdown table row per flagged item. */
function rows(list, cols) {
  return list.map((r) => "| " + cols.map((c) => String(r[c] ?? "")).join(" | ") + " |").join("\n");
}

/** Write the numbers as JSON and a flagged-items markdown summary. */
function report(res) {
  writeFileSync(resolve(HERE, `audit-${TAG}.json`), JSON.stringify(res, null, 1));
  const bad = (r) =>
    r.poke > 4 || r.bare > 4 || r.zfight > 4 || r.floating > 0 || r.floor > 0 || r.body > 4;
  const md = [
    `# Figures audit results (${TAG})`,
    "",
    "Generated by `audit.mjs` (head units: 0.01 = 1 cm before the head's 1.38 x scale). Head pieces: `zone` = head points the piece must cover, `poke` = of those, the piece is sunk under the head surface (the head shows through it), `bare` = nothing covers them, `zfight` = piece samples parallel to the head within 0.8 mm, `rimGap` = largest open-rim gap (mm), `floating` = rim points > 3 mm off the head. Poses: samples below the floor (> 3 mm) and head-piece samples inside the torso / upper arms. Flag: poke, bare, zfight or body > 4, any floating rim point, anything below the floor.",
    "",
    `Face band: ${JSON.stringify(res.faceBand)}`,
    "",
    "## Head pieces (standing, head space)",
    "| category | who | piece | zone | poke | bare | zfight | rimGap mm | floating |",
    "|---|---|---|---|---|---|---|---|---|",
    rows(res.pieces.filter(bad), [
      "cat",
      "who",
      "type",
      "zone",
      "poke",
      "bare",
      "zfight",
      "rimGap",
      "floating",
    ]),
    "",
    "## Poses (figure space)",
    "| category | who | pose | floor | parts below floor | piece in body |",
    "|---|---|---|---|---|---|",
    rows(res.poses.filter(bad), ["cat", "who", "pose", "floor", "floorParts", "body"]),
  ].join("\n");
  writeFileSync(resolve(HERE, `audit-results-${TAG}.md`), md + "\n");
  return { pieces: res.pieces.filter(bad).length, poses: res.poses.filter(bad).length };
}

/** Render every subject's contact sheet into figures/sheets-<tag>/. */
async function sheets(page) {
  const dir = resolve(HERE, `sheets-${TAG}`);
  mkdirSync(dir, { recursive: true });
  const names = await page.evaluate(() => window.KQAuditSubjects.names());
  for (const name of names) {
    const url = await page.evaluate((n) => window.KQAuditSubjects.sheet(n), name);
    writeFileSync(resolve(dir, name + ".jpg"), Buffer.from(url.split(",")[1], "base64"));
  }
  return names.length;
}

const browser = await chromium.launch(launchArgs());
try {
  const page = await openPage(browser);
  const res = await page.evaluate(() => window.KQAuditSubjects.checks());
  const flagged = report(res);
  console.log("flagged", JSON.stringify(flagged), "face band", JSON.stringify(res.faceBand));
  if (SHEETS) console.log("sheets", await sheets(page));
} finally {
  await browser.close();
}
